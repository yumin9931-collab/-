# 2. 데이터 수집 (2년 반: 2024-05-01 ~ 2026-11-16)
start_date = '2024-01-01' # 실적 발표일 전후 인덱스 조회를 위해 여유 있게 설정
end_date = '2026-11-16'

tickers = {'NAVER': '035420', 'Kakao': '035720'}
df_prices = pd.DataFrame()

for name, code in tickers.items():
    df = fdr.DataReader(code, start_date, end_date)
    df_prices[name] = df['Close']

# 3. 주요 실적 발표일 정의 (2024년 1분기 ~ 2026년 3분기 대략적인 공시일 기준)
# ※ 정확한 DART 공시 일자에 맞춰 날짜를 수정하여 정밀 분석할 수 있습니다.
earnings_dates = [
    '2024-05-10', # 24 Q1
    '2024-08-09', # 24 Q2
    '2024-11-08', # 24 Q3
    '2025-02-07', # 24 Q4
    '2025-05-09', # 25 Q1
    '2025-08-08', # 25 Q2
    '2025-11-06', # 25 Q3
    '2026-02-06', # 25 Q4
    '2026-05-08', # 26 Q1
    '2026-08-07', # 26 Q2
    '2026-11-06'  # 26 Q3
]

# 4. 실적 발표일 기준 사후 수익률(T+1, T+3, T+5) 계산 함수
results = []

for edate in earnings_dates:
    # 주가 데이터에 해당 날짜가 존재하는지 확인 (휴장일일 경우 Pandas 2.0+ 호환 방식으로 가장 가까운 영업일 매칭)
    try:
        idx = df_prices.index.get_indexer([pd.to_datetime(edate)], method='nearest')[0]
        if idx == -1:
            continue
    except Exception:
        continue

    # 발표 당일(T), T+1, T+3, T+5 영업일 인덱스 확보
    if idx + 5 >= len(df_prices):
        continue # 데이터 범위 초과 시 제외

    date_T = df_prices.index[idx]
    date_T1 = df_prices.index[idx + 1]
    date_T3 = df_prices.index[idx + 3]
    date_T5 = df_prices.index[idx + 5]

    for name in tickers.keys():
        p_T = df_prices.loc[date_T, name]
        p_T1 = df_prices.loc[date_T1, name]
        p_T3 = df_prices.loc[date_T3, name]
        p_T5 = df_prices.loc[date_T5, name]

        results.append({
            'Earnings_Date': date_T.strftime('%Y-%m-%d'),
            'Company': name,
            'Return_T1': (p_T1 / p_T - 1) * 100,
            'Return_T3': (p_T3 / p_T - 1) * 100,
            'Return_T5': (p_T5 / p_T - 1) * 100
        })

df_results = pd.DataFrame(results)
print("=== 실적 발표일별 단기 주가 수익률 (%) ===")
print(df_results.to_string(index=False))

