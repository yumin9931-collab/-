# 야후파이낸스 티커: NAVER ('035420.KS'), Kakao ('035720.KS')
tickers_yf = {'NAVER': '035420.KS', 'Kakao': '035720.KS'}
debt_ratios = {}

print("=== 최신 재무제표 기준 부채비율 산출 ===")
for name, ticker in tickers_yf.items():
    stock = yf.Ticker(ticker)
    bs = stock.balance_sheet

    # 가장 최근 연간 재무제표 기준 총부채와 자기자본 추출
    # (연결재무제표 기준 Total Liabilities와 Total Stockholder Equity)
    total_liab = bs.loc['Total Liabilities Net Minority Interest'].iloc[0] if 'Total Liabilities Net Minority Interest' in bs.index else bs.loc['Total Liabilities'].iloc[0]
    total_equity = bs.loc['Stockholders Equity'].iloc[0] if 'Stockholders Equity' in bs.index else bs.loc['Total Equity'].iloc[0]

    # 부채비율 (%) = (총부채 / 자기자본) * 100
    d_e_ratio = (total_liab / total_equity) * 100
    debt_ratios[name] = d_e_ratio
    print(f"• {name} 부채비율: {d_e_ratio:.2f}% (총부채: {total_liab:,.0f}원, 자기자본: {total_equity:,.0f}원)")

